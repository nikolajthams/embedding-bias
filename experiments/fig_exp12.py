"""Main-text figure: rejection rate under H0 against n for Experiment 1 (left, synthetic) and Experiment 2 (right, text).
Standard test with sufficient and insufficient encoders, and the robust test with a correct tolerance and with
a tolerance that is too small (half of the true insufficiency).
Reads saved results only (no recomputation):
  results/exp1_typeI_vs_n.csv, exp1_robust_test.csv, exp2_text_typeI.csv, exp2_text_rv_benchmark.csv, summary_exp2.json
Writes paper/figures/exp12_typeI.tex (pgfplots, what the paper inputs) and paper/figures/exp12_typeI.pdf (matplotlib preview).
Usage: python experiments/fig_exp12.py
"""
import sys, json; from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import numpy as np, pandas as pd, matplotlib; matplotlib.use("Agg"); import matplotlib.pyplot as plt
from matplotlib.lines import Line2D
from citext import plotting as P; from citext.paths import RESULTS_DIR, FIG_DIR
ALPHA = 0.05; NS1 = [500, 1000, 2000, 4000, 10000]; NS2 = [500, 1000, 2000, 4000, 10000]
REG = json.load(open(RESULTS_DIR / "summary_exp2.json"))["primary_regressor"]   # Experiment 2 regressor whose columns are plotted
light, dark = P.seq_colors(2)
STY = {"suff": dict(color=P.CAT[2], marker="s", linestyle="--"),
       "ins0": dict(color=light, marker="o", linestyle=":", markerfacecolor="white", markeredgecolor=light, markeredgewidth=1.2),
       "ins1": dict(color=dark, marker="o"),
       "rich": dict(color=P.INK2, marker="D", linestyle="-.", markersize=4),
       "rob_true": dict(color=P.CAT[1], marker="^"),
       "rob_half": dict(color=P.CAT[3], marker="^")}
# pgfplots counterparts of STY (colors are defined in the generated file)
PGF = {"suff": "color=cSuff, mark=square*, dashed, mark options={solid}",
       "ins0": "color=cInsZero, mark=*, densely dotted, mark options={solid, fill=white, line width=0.7pt}",
       "ins1": "color=cInsOne, mark=*",
       "rich": "color=cRich, mark=diamond*, dash dot, mark options={solid}, mark size=2pt",
       "rob_true": "color=cRobTrue, mark=triangle*, mark size=2.1pt",
       "rob_half": "color=cRobHalf, mark=triangle*, mark size=2.1pt"}
COLORS = {"cSuff": P.CAT[2], "cInsZero": light, "cInsOne": dark, "cRich": P.INK2, "cRobTrue": P.CAT[1], "cRobHalf": P.CAT[3],
          "cMuted": P.MUTED, "cInk": P.INK2, "cAxis": P.AXIS, "cGrid": P.GRID}
ORDER = ["suff", "ins0", "ins1", "rich", "rob_true", "rob_half"]       # legend order (matplotlib fills columns first)
ORDER_PGF = ["suff", "rich", "ins0", "rob_true", "ins1", "rob_half"]   # same layout, row-major for pgfplots
DRAW = ["rich", "ins1", "rob_half", "ins0", "suff", "rob_true"]          # drawing order, last on top


def labels(rich_dim):
    return {"suff": r"standard test, sufficient $\psi$",
            "ins0": r"standard test, insufficient $\psi$, $\lambda = 0$",
            "ins1": r"standard test, insufficient $\psi$, $\lambda = 1$",
            "rich": r"standard test, sufficient $\psi$, %d-dim. (text only)" % rich_dim,
            "rob_true": r"robust test, $B = $ true insufficiency",
            "rob_half": r"robust test, $B = $ half the true insufficiency"}


def exp1():
    t = pd.read_csv(RESULTS_DIR / "exp1_typeI_vs_n.csv"); r = pd.read_csv(RESULTS_DIR / "exp1_robust_test.csv").sort_values("n")
    g = lambda tag: t[t.tag == tag].sort_values("n")
    return {"suff": (g("sufficient (q=20)").n, g("sufficient (q=20)").rej), "ins0": (g("q=5, lam=0").n, g("q=5, lam=0").rej),
            "ins1": (g("q=5, lam=1").n, g("q=5, lam=1").rej), "rob_true": (r.n, r.robust_bound),
            "rob_half": (r.n, r.robust_half)}


def exp2():
    t = pd.read_csv(RESULTS_DIR / "exp2_text_typeI.csv")
    g = lambda psi, lam: t[(t.psi == psi) & (t.lam == lam)].sort_values("n")
    a = pd.read_csv(RESULTS_DIR / "exp2_text_rv_benchmark.csv").sort_values("n")   # written by exp2_text.py --only plots (primary regressor)
    summary = json.load(open(RESULTS_DIR / "summary_exp2.json"))
    print("exp2 (%s) robust test at the oracle tolerance and at half of it:" % REG, a[["n", "robust_bound_rej", "robust_half_rej"]].round(3).to_dict(orient="list"))
    rej = f"rej_{REG}"
    return {"suff": (g("oracle", 1.0).n, g("oracle", 1.0)[rej]), "ins0": (g("E1", 0.0).n, g("E1", 0.0)[rej]),
            "ins1": (g("E1", 1.0).n, g("E1", 1.0)[rej]), "rich": (g("rich", 1.0).n, g("rich", 1.0)[rej]),
            "rob_true": (a.n, a.robust_bound_rej), "rob_half": (a.n, a.robust_half_rej)}, int(summary["rich_encoder_dim"])


def write_pgfplots(data1, data2, rich_dim):
    lab = labels(rich_dim)
    coords = lambda xy: " ".join("(%d,%.4f)" % (int(x), float(y)) for x, y in zip(*xy) if np.isfinite(float(y)))   # unreported configurations are left out
    out = ["%% Generated by code/experiments/fig_exp12.py from code/results/*.csv (Experiment 2 regressor: %s). Do not edit by hand." % REG,
           "% Requires \\usepackage{pgfplots}, \\pgfplotsset{compat=1.18}, \\usepgfplotslibrary{groupplots}."]
    out += ["\\definecolor{%s}{HTML}{%s}" % (k, v.lstrip("#").upper()) for k, v in COLORS.items()]
    out += [r"\begin{tikzpicture}", r"\begin{groupplot}[",
            r"  group style={group size=2 by 1, horizontal sep=8mm, ylabels at=edge left, yticklabels at=edge left},",
            r"  width=0.5\linewidth, height=4cm,",
            r"  xmode=log, log ticks with fixed point, ymin=-0.02, ymax=1.02, ytick={0,0.2,0.4,0.6,0.8,1},",
            r"  xlabel={sample size $n$}, ylabel={rejection rate under $H_0$}, xlabel style={yshift=2pt},",
            r"  tick label style={font=\scriptsize}, label style={font=\footnotesize}, title style={font=\footnotesize, yshift=-3pt},",
            r"  axis lines*=left, axis line style={color=cAxis, line width=0.5pt}, tick style={color=cAxis},",
            r"  grid=major, grid style={color=cGrid, line width=0.4pt},",
            r"  every axis plot/.append style={line width=0.9pt, mark size=1.7pt},",
            r"  legend cell align=left, legend columns=2,",
            r"  legend style={font=\scriptsize, draw=none, fill=none, /tikz/every even column/.append style={column sep=5mm}},",
            r"]"]
    for k, (data, ns, title, extra) in enumerate(((data1, NS1, "Synthetic", ", legend to name=exp12legend"), (data2, NS2, "Text", ""))):
        xmin, xmax = ns[0] / 1.16, ns[-1] * 1.16
        ticks = ",".join(str(n) for n in ns)
        out.append(r"\nextgroupplot[title={%s}, xmin=%.0f, xmax=%.0f, xtick={%s}, xticklabels={%s}%s]" % (title, xmin, xmax, ticks, ticks, extra))
        out.append(r"\addplot[color=cMuted, dashed, line width=0.5pt, forget plot] coordinates {(%.0f,%.2f) (%.0f,%.2f)};" % (xmin, ALPHA, xmax, ALPHA))
        out.append(r"\node[anchor=south east, font=\tiny, text=cInk, inner sep=1pt] at (axis cs:%d,%.2f) {$\alpha = %.2f$};" % (ns[-1], ALPHA, ALPHA))
        for key in DRAW:
            if key in data:
                out.append(r"\addplot[%s, forget plot] coordinates {%s};" % (PGF[key], coords(data[key])))
        if k == 0:
            for key in ORDER_PGF:
                out.append(r"\addlegendimage{%s}\addlegendentry{%s}" % (PGF[key], lab[key]))
    out += [r"\end{groupplot}",
            r"\path (group c1r1.outer south west) -- (group c2r1.outer south east) node[midway, anchor=north, yshift=-2pt] {\pgfplotslegendfromname{exp12legend}};",
            r"\end{tikzpicture}", ""]
    path = FIG_DIR / "exp12_typeI.tex"; path.write_text("\n".join(out)); print(path)


def preview(data1, data2, rich_dim):
    lab = labels(rich_dim)
    P.setup(); fig, axes = plt.subplots(1, 2, figsize=(6.6, 2.45), sharey=True)
    for ax, data, ns, title in zip(axes, (data1, data2), (NS1, NS2), ("Synthetic", "Text")):
        for key in DRAW:
            if key in data:
                x, y = data[key]; ax.plot(x, y, **STY[key], zorder=3 if key in ("ins0", "suff", "rob_true") else 2)
        ax.axhline(ALPHA, color=P.MUTED, linewidth=0.8, linestyle="--", zorder=1)
        ax.annotate(r"$\alpha=0.05$", (ns[-1], ALPHA), xytext=(-2, 3), textcoords="offset points", fontsize=6.5, color=P.INK2, ha="right")
        ax.set_xscale("log"); ax.set_xticks(ns); ax.set_xticklabels([str(n) for n in ns]); ax.minorticks_off()
        ax.set_xlabel(r"sample size $n$"); ax.set_ylim(-0.02, 1.02); ax.set_title(title)
    axes[0].set_ylabel("rejection rate under $H_0$")
    handles = [Line2D([0], [0], **STY[k]) for k in ORDER]
    fig.legend(handles, [lab[k] for k in ORDER], loc="lower center", ncol=2, bbox_to_anchor=(0.5, -0.02), fontsize=6.5,
               frameon=False, handlelength=2.2, columnspacing=1.6)
    fig.subplots_adjust(bottom=0.36, wspace=0.12)
    P.savefig(fig, "exp12_typeI.pdf"); print("exp12_typeI.pdf (preview)")


def main():
    data1 = exp1(); data2, rich_dim = exp2()
    write_pgfplots(data1, data2, rich_dim); preview(data1, data2, rich_dim)


if __name__ == "__main__":
    main()
